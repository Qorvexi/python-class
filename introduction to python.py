# INSTALLING PYTHON

# Step 1
# Python is not usually installed on a new computer, so the first step is to install it.
# During installation, there is one very important checkbox: ✅ Add python to path.
# if you forget to tick this box, your computer may not recognize python when you type python on the terminal.

# Step 2
# Check if python is installed
# Open command promopt or cmd
# type: python --version or python --v
# If you see a version number, Python is installed successfully.