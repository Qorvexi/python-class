# PYTHON VARIABLES
# A variable is a container that stores value or data

# CREATING A VARIABLE
# SYNTAX: variable_name = value

# Example:
name = "Chigozie"

# name - variable
# "Chigozie" - is the value
# = - assignment operator (stores the value in the variable)

# PRINTING VARIABLES
print(name)

